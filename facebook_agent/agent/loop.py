FOLD_CHARS = str.maketrans({"’": "'", "‐": "-", "‑": "-", " ": " ", " ": " "})


def fold(text: str) -> str:
    """Text without accents, with straight apostrophes and plain hyphens and spaces (keyword and verb checks).

    « Enlève », « enleve » and « ENLÈVE » then match the same pattern. Each accented letter stays one letter,
    so the positions in the text do not move.

    Args:
        text: Request of the user, or the source of a pattern.

    Returns:
        The folded text.
    """
    decomposed = unicodedata.normalize("NFD", text)
    return unicodedata.normalize("NFC", "".join(c for c in decomposed if not unicodedata.combining(c))) \
        .translate(FOLD_CHARS)


def folded(pattern: str, flags: int = re.IGNORECASE) -> re.Pattern:
    """A pattern written with accents, compiled without them: it is matched against fold(text).

    Args:
        pattern: Regular expression (accents allowed, e.g. « vidéos? »).
        flags: re flags (case ignored by default).

    Returns:
        The compiled pattern.
    """
    return re.compile(fold(pattern), flags)


