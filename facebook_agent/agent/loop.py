    def reset(self) -> None:
        """Empty the history and forget the IDs seen (/reset)."""
        self.history.reset()
        self.executor.known_ids.clear()
        self.executor.result_ids.clear()  # provenance des campagnes et Lead Ads : tout est à relire après /reset
        self.executor.comment_authors.clear()
        self.previous_route = None
        self.recent_actions = []
        self.boost_details_asked = False
        self._log("reset")

    def status_line(self) -> str:
        """Line shown after each answer: estimated context and tokens left today.

        Returns:
            "Contexte : N tokens (estimation) | Restant aujourd'hui : M tokens".
        """
        context = self.context_tokens()
        warning = " (proche de la limite par minute : /reset conseillé)" if context > TOKENS_PER_MINUTE * 0.6 else ""
        quota = self.quota_left()
        if len(quota) == 1:
            left = f"{next(iter(quota.values()))} tokens"
        else:  # un quota par modèle
            left = " | ".join(f"{m.split('/')[-1]} : {value}" for m, value in quota.items()) + " tokens"
        return f"Contexte : {context} tokens (estimation){warning} | Restant aujourd'hui : {left}"

    def context_tokens(self) -> int:
        """Estimated tokens of the context sent with the next request (system prompt and history).

        Returns:
            The estimate.
        """
        return self.history.estimate_tokens(build_system_prompt(dry_run=self.dry_run, cards=self.cards_mode))

    def quota_left(self) -> dict[str, int]:
        """Groq tokens left today, per model (the main model and the router model each have their quota).

        Without a log, only the tokens of this session are counted.

        Returns:
            {model: tokens left}, one entry when there is one model or no log.
        """
        models = list(dict.fromkeys(m for m in (self.model, self.router_model) if m))
        if not self.journal or not models:
            return {self.model or "": max(self.tokens_per_day - self.session_tokens, 0)}
        if len(models) == 1:
            return {models[0]: max(self.tokens_per_day - tokens_used_today(self.journal.log_dir), 0)}
        return {m: max(self.tokens_per_day - tokens_used_today(self.journal.log_dir, model=m,
                                                               default_model=self.model), 0) for m in models}
