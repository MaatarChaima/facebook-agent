    # --- Journal ----------------------------------------------------------------------------
    def _log(self, event: str, **fields) -> None:
        """Write an event in the session log, if there is one; a 429 on the tokens per day keeps Groq's count."""
        if event == "rate_limit" and fields.get("limit") == LIMIT_NAMES["TPD"]:
            self._remember_groq_quota(fields)
        if self.journal:
            self.journal.write(event, **fields)

    def _tokens_today(self, model: str | None) -> int:
        """Tokens of a model counted locally today (logs of every session, or this session without a log)."""
        if not self.journal:
            return self.session_tokens
        return tokens_used_today(self.journal.log_dir, model=model, default_model=self.model)

    def _remember_groq_quota(self, fields: dict) -> None:
        """Keep the daily quota given by Groq in a 429 answer ("Limit 200000, Used 199135").

        Args:
            fields: Fields of the "rate_limit" event (model, groq_limit, groq_used).
        """
        used, limit, model = fields.get("groq_used"), fields.get("groq_limit"), fields.get("model")
        if not isinstance(used, int) or not isinstance(limit, int) or not model:
            return
        now = datetime.now()
        self.groq_reported[model] = {"used": used, "limit": limit, "local": self._tokens_today(model),
                                     "day": now.date(), "time": now.strftime("%H:%M")}

    def groq_quota(self) -> dict[str, tuple[int, int, str]]:
        """Tokens left today according to Groq, for the models that got a 429 on the tokens per day today.

        Groq's count of that moment, minus the tokens used since then (counted locally).

        Returns:
            {model: (tokens left, daily limit, "HH:MM" of Groq's answer)}.
        """
        today = datetime.now().date()
        found = {}
        for model, reported in self.groq_reported.items():
            if reported["day"] != today:
                continue
            since = max(self._tokens_today(model) - reported["local"], 0)
            found[model] = (max(reported["limit"] - reported["used"] - since, 0), reported["limit"], reported["time"])
        return found

