def order_parts(user_text: str) -> tuple[tuple, str] | None:
    """The verb of an explicit order and the rest of the request, or None when it is not an order.

    The verb must start the request, after a greeting and a formula (« Bonjour, peux-tu supprimer… »,
    « Can you delete… »); conjugated (« Supprime »), infinitive (« Supprimer ») or English (« Delete »),
    with or without accents.

    Args:
        user_text: The request.

    Returns:
        (entry of VERB_TOOLS, folded text after the verb), or None.
    """
    plain = ORDER_PREFIX.sub("", fold(user_text), count=1)
    for entry in VERB_TOOLS:
        match = entry[0].match(plain)
        if match:
            return entry, plain[match.end():]
    return None


def is_order(user_text: str) -> bool:
    """Whether a request is an explicit order (a verb of VERB_TOOLS at its start).

    Args:
        user_text: The request.

    Returns:
        True for « Supprime le post… », « Peux-tu supprimer… », « Supprimer le post… », « Delete the post… ».
    """
    return order_parts(user_text) is not None
