import json

from facebook_agent.graph import call_graph, check_required, error, validation_error

CREATE_ERROR = "Échec de la création du lead de test."


def _field_data_errors(field_data) -> list[str]:
    """Validation errors of the answers of a test lead (empty list = valid)."""
    if not isinstance(field_data, list) or not field_data:
        return ["field_data doit être une liste d'au moins une réponse {\"name\", \"values\"}."]
    errors, seen = [], set()
    for index, answer in enumerate(field_data, 1):
        where = f"réponse {index}"
        if not isinstance(answer, dict) or set(answer) != {"name", "values"}:
            errors.append(f"{where} : un objet {{\"name\", \"values\"}} est attendu.")
            continue
        name, values = answer["name"], answer["values"]
        if not isinstance(name, str) or not name.strip():
            errors.append(f"{where} : name est obligatoire (la key d'une question du formulaire).")
        elif name in seen:
            errors.append(f"{where} : la question {name!r} a déjà une réponse.")
        else:
            seen.add(name)
        if not isinstance(values, list) or not values or not all(isinstance(v, str) and v.strip() for v in values):
            errors.append(f"{where} : values doit être une liste non vide de textes.")
    return errors


def create_test_lead(form_id: str, page_token: str, field_data: list | None = None) -> dict:
    """Create a test lead on a Lead Ads form, to check the form without a real person.

    Sends POST /{form_id}/test_leads. When field_data is given, the questions of the form are read
    first (GET /{form_id}?fields=questions) and every name must be the key of one of them. Meta
    allows one test lead per form: delete it first (delete_test_lead) to create another one.
    Requires a Page access token of a person with the ADVERTISE task (or above) on the page that
    owns the form.

    Parameters:
        - Input-form_id (str, mandatory): ID of the Lead Ads form.
          Example: "LEAD_FORM_ID_EXAMPLE"
        - Input-page_token (str, mandatory): Page access token of the page that owns the form.
        - Input-field_data (list[dict], optional): Answers of the test lead, one per question key
          of the form; empty = answers generated by Facebook. Never put a real person's data here.
          Keys:
              - Key-name (str, mandatory): Key of the question (as in create_lead_form).
              - Key-values (list[str], mandatory): Answer(s) to the question.
          Example: [{"name": "nom", "values": ["Client Test"]}, {"name": "email", "values": ["client.test@example.com"]}]

    Returns:
        dict: {"status": "success", "data": ...} or {"status": "error", "message": ..., "details": {...}}
        Output type: dict, the raw Graph API answer: {"id": "<id of the test lead>"} (Meta documents
            no example of this answer; confirmed by the capture of 2026-10-24).
        Example (success):
            {
                "status": "success",
                "data": {
                    "id": "LEAD_ID_EXAMPLE"
                }
            }
        Errors:
            - validation: form_id or page_token is empty; an item of field_data without name or
              with values that are not a non-empty list of texts; a name used twice; a name that is
              not the key of a question of the form (the error lists the valid keys; the questions
              are read first, no test lead is sent).
            - api: reading the questions of the form failed, or the Graph API returned an error
              (details.status_code, details.error), e.g. a test lead already exists for this form,
              or answered without id (details.response).
            - timeout, network, invalid_response: the API did not answer in time, could not be
              reached, or did not return JSON.
            - unexpected: any other exception (details.info).
    """
    try:
        if invalid := check_required(form_id=form_id, page_token=page_token):
            return invalid
        data = {}
        if field_data is not None:
            if errors := _field_data_errors(field_data):
                return validation_error(errors, message="Des erreurs ont été détectées dans les réponses du lead de test.")
            # Les noms doivent être les clés des questions du formulaire : relues avant l'envoi
            form = call_graph("GET", form_id, page_token, params={"fields": "questions"},
                              error_message="Lecture des questions du formulaire impossible.")
            if form["status"] == "error":
                return form
            keys = [q.get("key") for q in (form["data"].get("questions") or []) if isinstance(q, dict)]
            unknown = [answer["name"] for answer in field_data if answer["name"] not in keys]
            if unknown:
                return validation_error(
                    [f"{name!r} n'est pas une clé de question du formulaire." for name in unknown]
                    + [f"Clés valides : {', '.join(map(str, keys)) or '(aucune question lue)'}"],
                    message="Certaines réponses ne correspondent à aucune question du formulaire.")
            data["field_data"] = json.dumps(field_data, ensure_ascii=False)
        result = call_graph("POST", f"{form_id}/test_leads", page_token, data=data, error_message=CREATE_ERROR)
        if result["status"] == "success" and not result["data"].get("id"):
            return error(CREATE_ERROR, {"type": "api", "response": result["data"]})
        return result
    except Exception as e:
        return error("Une erreur inattendue est survenue", {"type": "unexpected", "info": str(e)})
